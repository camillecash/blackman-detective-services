const fs = require("fs");
const path = require("path");

const root = __dirname;
const outputFile = path.join(root, "search-index.js");

const pageLabels = {
  "": "Home",
  about: "About",
  contact: "Contact",
  faq: "FAQ",
  payments: "Payments",
  "payments/ach": "ACH Payment",
  "payments/credit-card": "Credit Card Payment",
  "privacy-policy": "Privacy Policy",
  services: "Services",
  "the-sleuth": "The Sleuth"
};

const skipFiles = new Set(["privacy-policy.html"]);

function walk(directory) {
  return fs.readdirSync(directory).reduce((files, entry) => {
    const fullPath = path.join(directory, entry);
    const stats = fs.statSync(fullPath);
    if (stats.isDirectory()) {
      if (entry === "assets" || entry === ".git") return files;
      return files.concat(walk(fullPath));
    }
    if (stats.isFile() && entry.endsWith(".html")) files.push(fullPath);
    return files;
  }, []);
}

function decodeEntities(value) {
  const named = {
    amp: "&",
    apos: "'",
    bull: " ",
    copy: "copyright",
    gt: ">",
    ldquo: '"',
    lsquo: "'",
    lt: "<",
    mdash: "-",
    nbsp: " ",
    ndash: "-",
    quot: '"',
    rdquo: '"',
    rsquo: "'"
  };

  return value.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (_, entity) => {
    if (entity[0] === "#") {
      const isHex = entity[1] && entity[1].toLowerCase() === "x";
      const code = Number.parseInt(entity.slice(isHex ? 2 : 1), isHex ? 16 : 10);
      return Number.isFinite(code) ? String.fromCodePoint(code) : " ";
    }
    return named[entity.toLowerCase()] || " ";
  });
}

function cleanText(html) {
  return decodeEntities(
    html
      .replace(/<script[\s\S]*?<\/script>/gi, " ")
      .replace(/<style[\s\S]*?<\/style>/gi, " ")
      .replace(/<svg[\s\S]*?<\/svg>/gi, " ")
      .replace(/<iframe[\s\S]*?<\/iframe>/gi, " ")
      .replace(/<form[\s\S]*?<\/form>/gi, " ")
      .replace(/<[^>]+>/g, " ")
  )
    .replace(/\s+/g, " ")
    .trim();
}

function titleFrom(html, fallback) {
  const match = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  if (!match) return fallback;
  return cleanText(match[1]).replace(/\s*\|\s*Blackman Detective Services\s*$/i, "").trim() || fallback;
}

function pagePath(file) {
  const relative = path.relative(root, file).replace(/\\/g, "/");
  if (relative === "index.html") return "";
  return relative.replace(/\/index\.html$/, "").replace(/\.html$/, "");
}

function chunksFrom(html) {
  const mainMatch = html.match(/<main[^>]*>([\s\S]*?)<\/main>/i);
  const source = mainMatch ? mainMatch[1] : html;
  const pieces = [];
  const piecePattern = /<(h[1-4]|p|li|summary|blockquote)[^>]*>([\s\S]*?)<\/\1>/gi;
  let match;

  while ((match = piecePattern.exec(source))) {
    const text = cleanText(match[2]);
    if (text.length > 24 && !/^menu$/i.test(text)) pieces.push(text);
  }

  if (!pieces.length) {
    const text = cleanText(source);
    if (text) pieces.push(text);
  }

  const chunks = [];
  let current = "";

  pieces.forEach((piece) => {
    if ((current + " " + piece).trim().length > 650 && current) {
      chunks.push(current.trim());
      current = piece;
    } else {
      current = `${current} ${piece}`.trim();
    }
  });

  if (current) chunks.push(current.trim());
  return chunks;
}

function keywordsFor(text, title, label) {
  const stopwords = new Set([
    "about", "after", "also", "and", "are", "blackman", "bds", "can", "detective", "for", "from", "has", "have", "into", "its", "our", "services", "that", "the", "their", "this", "with", "your"
  ]);
  const words = `${title} ${label} ${text}`
    .toLowerCase()
    .replace(/[^a-z0-9\s'-]/g, " ")
    .split(/\s+/)
    .filter((word) => word.length > 3 && !stopwords.has(word));
  return Array.from(new Set(words)).slice(0, 28);
}

const index = [].concat.apply([], walk(root)
  .filter((file) => !skipFiles.has(path.relative(root, file).replace(/\\/g, "/")))
  .map((file) => {
    const html = fs.readFileSync(file, "utf8");
    const page = pagePath(file);
    const label = pageLabels[page] || titleFrom(html, page || "Home");
    const title = titleFrom(html, label);

    return chunksFrom(html).map((text, position) => ({
      title,
      page: label,
      path: page,
      label: `View ${label}`,
      keywords: keywordsFor(text, title, label),
      text,
      position
    }));
  }));

const file = `// Generated by build-search-index.js. Re-run after editing page content.\nwindow.BDS_SEARCH_INDEX = ${JSON.stringify(index, null, 2)};\n`;
fs.writeFileSync(outputFile, file);
console.log(`Generated ${index.length} search entries in ${path.relative(root, outputFile)}`);
